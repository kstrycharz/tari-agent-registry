"""Refresh cross-platform hashes from PyPI for already resolved wheel versions.

Maintainers: first pip download --only-binary=:all: --dest .deps <pins>.
Review version changes and regenerate this lock when updating requirements.
"""
import json
from pathlib import Path
from urllib.request import urlopen


def main():
    lines = ["# Generated by tools/lock_dependencies.py; review versions before merging."]
    for wheel in sorted(Path(".deps").glob("*.whl")):
        name, version = wheel.name.split("-")[:2]
        # Distribution names and versions come from wheel basenames, never PR data.
        url = f"https://pypi.org/pypi/{name}/{version}/json"
        with urlopen(url, timeout=30) as response:  # nosec B310 - fixed HTTPS PyPI origin
            meta = json.load(response)
        hashes = sorted({item["digests"]["sha256"] for item in meta["urls"]})
        lines.append(f"{name.replace('_', '-')}=={version} \\")
        lines.extend(f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes))
    Path("requirements-ci.lock").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
